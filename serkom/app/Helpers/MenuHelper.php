    /**
     * Filter menu items berdasarkan role user.
     * Case-insensitive — 'admin' akan match dengan 'Admin'.
     */
    private static function filterByRole(array $items, ?string $role): array
    {
        if (!$role) return [];

        return array_values(array_filter($items, function ($item) use ($role) {
            // Kalau tidak ada 'roles' → anggap semua bisa akses
            if (empty($item['roles'])) return true;

            // Case-insensitive compare
            $allowed = array_map('strtolower', $item['roles']);
            return in_array(strtolower($role), $allowed, true);
        }));
    }

    /**
     * Cek apakah menu aktif berdasarkan path saat ini.
     * Support exact match + sub-path.
     */
    public static function isActive(string $path): bool
    {
        $current = '/' . ltrim(request()->path(), '/');

        // Root path — harus exact
        if ($path === '/') {
            return $current === '/';
        }

        // Exact atau sub-path
        return $current === $path || str_starts_with($current, $path . '/');
    }

